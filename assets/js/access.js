/* ============================================================
   访问模式开关（单一来源）
   ------------------------------------------------------------
   这是「要不要登录」的唯一开关。前端、服务端、构建脚本都读它，
   避免出现「界面放开了但服务端还在拦」这类不一致。

     open: true   —— 公开访问（当前设置）
       门户与学习项目都不校验登录，任何人打开即可浏览。
       适用于 GitHub Pages 这类没有服务端的静态托管。

     open: false  —— 恢复登录门禁
       前端会请求 /api/session，由 server/auth.mjs 提供账号服务；
       需要 Node 运行环境与持久化磁盘（见 README）。

   【为什么做成开关，而不是把认证删掉】
   账号体系、用户管理、scrypt 哈希这些代码都完整保留着。
   把它改回 false，并执行 `npm run build:pages` 前先在服务器本机
   初始化 admin 密码，就能原样恢复登录。
   ============================================================ */

export const ACCESS = {
  open: true,

  /* 公开访问时，页面上是否显示「管理员登录」之类的入口。
     留一个 false 可以在不恢复门禁的前提下，让运维仍能登录管理。 */
  showAccountUI: false
};
